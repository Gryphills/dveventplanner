let safetyCycle = 0;
function cycleItems() {
  let eventObj = JSON.parse(localStorage.getItem('dvEvents'))
  if (!eventObj) {
    checkData()
    eventObj = JSON.parse(localStorage.getItem('dvEvents'))
  }
  let halloween26 = eventObj.halloween26
  let itemNames = Object.getOwnPropertyNames(eventData)
  //console.log("length of " , itemNames.length);
  for (i=0; i < itemNames.length; i++){
    let thisItem = eventData[itemNames[i]]
    if (i == 0) {
      safetyCycle += 1
    }
    if (safetyCycle > 1) {
      console.log('ohGOD we in a LOOP!');
      break;
    }
    let itemHtmElement = buildTemplate(itemNames[i], thisItem)
    if (!itemHtmElement.classList.contains('item')) {
      itemHtmElement = itemHtmElement.querySelector('.item');
    }
    document.getElementById('neutraldiv').appendChild(itemHtmElement)
    let numberEl =  itemHtmElement.querySelector('.purchasenum')
    numberEl.dataset.itemName = itemNames[i]

    numberEl.addEventListener('change', function(e) {
      let itemName = e.currentTarget.dataset.itemName
      //console.log('changed number!');
      saveCount(itemName, e.currentTarget.value)
      let idText = itemName.trim().replaceAll(' ', "-")
      idText = idText.replaceAll(`'`, '')
      idText = idText.replaceAll(`:`, '')
      let calcDiv = document.getElementById('itemstobuy');
      if (e.currentTarget.value != 0) {
         e.currentTarget.closest('.item').classList.add('withcount');
        let listItem;
        if (!calcDiv.querySelector(`#${idText}`)) {
          listItem = document.createElement('p');
          listItem.classList.add('itemprice');
          calcDiv.appendChild(listItem);
          listItem.id = idText;

        } else {
          listItem = calcDiv.querySelector(`#${idText}`)
        }
        let calculated = 0
        calculated = Number(thisItem.price) * Number(e.currentTarget.value)
        
        listItem.textContent = `${calculated} - ${e.currentTarget.value}x ${itemName}`;
        if (thisItem.type == "dragon") {
          listItem.textContent += ` Dragon`
        }
        listItem.dataset.subcost = calculated;
        let newhtml = `<div style='width: 35px; height: 35px;  display: inline-block;  vertical-align: center; margin-left: 8px;'>`
        if (thisItem.imgposted) {
          newhtml += `<img src="${thisItem.imgposted[0]}" width="30px" style="object-fit: contain; height: 100%;  width: 100%;">`
        }
        newhtml += `</div>`
        listItem.innerHTML += newhtml
      } else {
        e.currentTarget.closest('.item').classList.remove('withcount');
        if (calcDiv.querySelector(`#${idText}`)) {
          calcDiv.querySelector(`#${idText}`).remove();
        }
      }
      updateCalculationTotal();
    })
    //console.log('done w ' + itemNames[i] + '; charlatancount is ' + charlatancount.toString())
  }
}

